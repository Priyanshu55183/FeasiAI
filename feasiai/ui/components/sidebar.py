"""
Sidebar component: file upload, pipeline runner, and settings.
"""

from __future__ import annotations

import json
import logging
import os
import tempfile
from pathlib import Path

import streamlit as st

from feasiai.ui.utils import init_session_state, load_report_from_json

logger = logging.getLogger(__name__)


def render_sidebar() -> None:
    """Render the sidebar with upload, settings, and pipeline runner."""
    init_session_state(st)

    with st.sidebar:
        st.title("🤖 FeasiAI")
        st.caption("AI Solution Feasibility & Proposal Copilot")
        st.divider()

        # ── Upload mode ──────────────────────────────────────────────
        st.subheader("📂 Load Report")
        uploaded_file = st.file_uploader(
            "Upload a JSON report",
            type=["json"],
            help="Upload a report generated by `run_pipeline.py --json-output`",
        )

        if uploaded_file is not None:
            try:
                json_data = json.loads(uploaded_file.read())
                report = load_report_from_json(json_data)
                st.session_state.report = report
                st.session_state.overrides = {}
                st.session_state.notes = {}
                st.success(
                    f"✅ Loaded report: {report.source_document or 'Unknown'} "
                    f"({len(report.requirements)} requirements)"
                )
            except Exception as e:
                st.error(f"❌ Failed to load report: {e}")

        st.divider()

        # ── Live pipeline mode ───────────────────────────────────────
        st.subheader("🚀 Run Pipeline")

        rfp_input_method = st.radio(
            "RFP input method",
            ["Upload file", "Paste text"],
            horizontal=True,
            label_visibility="collapsed",
        )

        rfp_file = None
        rfp_text = None

        if rfp_input_method == "Upload file":
            rfp_file = st.file_uploader(
                "Upload RFP document",
                type=["pdf", "docx", "txt", "md"],
                key="rfp_upload",
                help="Supported formats: PDF, DOCX, TXT, MD",
            )
        else:
            rfp_text = st.text_area(
                "Paste RFP text",
                height=150,
                placeholder="Paste your RFP requirements here...",
            )

        # API key
        api_key = st.text_input(
            "Groq API Key",
            type="password",
            help="Optional — falls back to .env file",
            placeholder="gsk_...",
        )

        # Settings
        with st.expander("⚙️ Settings"):
            use_agent = st.toggle(
                "Use Planner Agent",
                value=True,
                help="Multi-step reasoning (Phase 2). Disable for single-shot.",
            )
            max_steps = st.slider(
                "Agent max steps",
                min_value=1,
                max_value=5,
                value=3,
                help="Max tool calls per requirement",
                disabled=not use_agent,
            )
            confidence_threshold = st.slider(
                "Early stop confidence",
                min_value=0.5,
                max_value=1.0,
                value=0.85,
                step=0.05,
                help="Agent stops early above this confidence",
                disabled=not use_agent,
            )

        # Run button
        can_run = bool(rfp_file or (rfp_text and rfp_text.strip()))
        if st.button(
            "🚀 Run Pipeline",
            type="primary",
            disabled=not can_run,
            use_container_width=True,
        ):
            _run_pipeline(
                rfp_file=rfp_file,
                rfp_text=rfp_text,
                api_key=api_key or None,
                use_agent=use_agent,
                max_steps=max_steps,
                confidence_threshold=confidence_threshold,
            )

        # ── Demo mode ────────────────────────────────────────────────
        st.divider()
        if st.button(
            "📋 Load Demo Report",
            use_container_width=True,
            help="Load a sample report to explore the UI",
        ):
            _load_demo_report()


def _run_pipeline(
    rfp_file,
    rfp_text: str | None,
    api_key: str | None,
    use_agent: bool,
    max_steps: int,
    confidence_threshold: float,
) -> None:
    """Run the feasibility pipeline and store the report."""
    with st.sidebar:
        with st.status("Running pipeline...", expanded=True) as status:
            try:
                # Set API key if provided
                if api_key:
                    os.environ["GROQ_API_KEY"] = api_key

                from feasiai.llm.client import LLMClient
                from feasiai.pipeline import FeasibilityPipeline
                from feasiai.retrieval.memory_store import MemoryStore

                st.write("🔧 Initializing pipeline...")
                llm = LLMClient(api_key=api_key) if api_key else LLMClient()
                memory = MemoryStore()
                pipeline = FeasibilityPipeline(
                    llm_client=llm,
                    memory_store=memory,
                    use_agent=use_agent,
                )

                st.write("📚 Loading institutional memory...")
                pipeline.initialize()

                st.write("📄 Processing RFP...")
                if rfp_file is not None:
                    # Save uploaded file to temp location
                    suffix = Path(rfp_file.name).suffix
                    with tempfile.NamedTemporaryFile(
                        delete=False, suffix=suffix
                    ) as tmp:
                        tmp.write(rfp_file.read())
                        tmp_path = tmp.name

                    report = pipeline.run(
                        input_path=tmp_path,
                        source_name=rfp_file.name,
                    )
                    os.unlink(tmp_path)
                else:
                    report = pipeline.run(
                        input_text=rfp_text,
                        source_name="pasted_text",
                    )

                st.session_state.report = report
                st.session_state.overrides = {}
                st.session_state.notes = {}
                status.update(
                    label="✅ Pipeline complete!",
                    state="complete",
                )
                st.rerun()

            except Exception as e:
                status.update(label="❌ Pipeline failed", state="error")
                st.error(f"Error: {e}")
                logger.exception("Pipeline failed")


